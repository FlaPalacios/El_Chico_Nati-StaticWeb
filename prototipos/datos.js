// Foto de Cloudinary: recorta el blanco sobrante (e_trim) y ajusta tamaño.
//   modo 'silueta': alto fijo, ancho libre (para repisas y composiciones)
//   modo 'cuadro' : cuadrado con margen blanco parejo (para tarjetas)
window.ECN.foto = function (url, tam, modo) {
  var t = modo === 'silueta'
    ? 'e_trim/h_' + tam + ',c_scale/f_auto,q_auto'
    : 'e_trim/c_pad,w_' + tam + ',h_' + tam + ',b_white/f_auto,q_auto';
  return url.replace('/upload/', '/upload/' + t + '/');
};
window.ECN.soles = function (n) { return 'S/ ' + n.toFixed(2); }; // espacio irrompible: "S/" nunca queda solo al final de línea
window.ECN.buscar = function (codigo) {
  return window.ECN.productos.find(function (p) { return p.codigo === codigo; });
};
